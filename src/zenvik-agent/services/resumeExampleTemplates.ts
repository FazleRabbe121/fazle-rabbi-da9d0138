export function getResumeTemplateById(id?: string): ResumeExampleTemplateDefinition {
  if (!id) {
    return RESUME_EXAMPLE_TEMPLATES.find(t => t.id === 'classic-hospitality') || RESUME_EXAMPLE_TEMPLATES[0];
  }
  return (
    RESUME_EXAMPLE_TEMPLATES.find(t => t.id === id) ||
    RESUME_EXAMPLE_TEMPLATES.find(t => t.id === 'classic-hospitality') ||
    RESUME_EXAMPLE_TEMPLATES[0]
  );
}
